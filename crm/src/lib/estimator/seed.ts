import type { EstimatorDocument, EstimatorOption, EstimatorQuestion, QuestionKey } from './document'

type O = Omit<EstimatorOption, 'enabled' | 'price'> & { price?: Record<string, number>; enabled?: boolean }
const opts = (list: O[]): EstimatorOption[] => list.map((o) => ({ enabled: true, price: {}, ...o }))
const q = (key: QuestionKey, label: string, options?: O[], help?: string): EstimatorQuestion => ({
  key,
  label,
  ...(help ? { help } : {}),
  default: null,
  ...(options ? { options: opts(options) } : {}),
})
const yesNoUnsure = (yesFlag?: string): O[] => [
  { value: 'yes', label: 'Yes', ...(yesFlag ? { reviewFlag: yesFlag } : {}) },
  { value: 'no', label: 'No' },
  { value: 'unsure', label: 'Not sure' },
]

